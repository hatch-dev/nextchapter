/* build-templates.js — regenerates templates-local.js from the screen .html files.
   templates-local.js lets the app run from disk (file://), where browsers block
   fetch of local files. Run after editing any screen's .html:
     node build-templates.js */
const fs=require('fs');
/* Prefix derives from this file's own name (ER seam pattern): named
   DL-build-templates.js it reads DL-<name>.html and writes DL-templates-local.js;
   named canonically it reads/writes canonical names. Bundle KEYS stay unprefixed. */
const PFX=require('path').basename(__filename).replace('build-templates.js','');
const SCREENS=['home','learn'];
const out={};
SCREENS.forEach(function(n){out[n]=fs.readFileSync(PFX+n+'.html','utf8')});
fs.writeFileSync(PFX+'templates-local.js','/* Generated by '+PFX+'build-templates.js \u2014 do not edit by hand.\n   Source of truth: the '+PFX+'<name>.html screen files. Regenerate after editing them:\n   node '+PFX+'build-templates.js */\nwindow.__LOCAL_TEMPLATES = '+JSON.stringify(out)+';\n');
console.log(PFX+'templates-local.js written for: '+SCREENS.join(', '));
