#!/usr/bin/env node
/* ─────────────────────────────────────────────────────────────
   build-templates.js — regenerates templates-local.js
   ─────────────────────────────────────────────────────────────
   The per-screen .html files are the single source of truth for
   markup. This script bundles them into templates-local.js so the
   app also runs when index.html is opened directly from disk
   (file://), where browsers block fetch().

   Run after editing any screen's .html file:

       node build-templates.js

   When adding a new screen (e.g. pipeline.html + pipeline.js),
   add its name to SCREENS below and re-run.
   ───────────────────────────────────────────────────────────── */
'use strict';
const fs = require('fs');
const path = require('path');

// This script lives in tools/. The screen markup is in ../templates/ and the
// generated bundle is written to ../js/ (loaded by index.html before app.js).
const TEMPLATES_DIR = path.join(__dirname, '..', 'templates');
const OUTPUT_FILE = path.join(__dirname, '..', 'js', 'templates-local.js');

const SCREENS = ['home', 'learn', 'insights', 'login', 'setup', 'admin-login', 'choose-password', 'nav'];

let out =
  '/* AUTO-GENERATED by build-templates.js — DO NOT EDIT BY HAND.\n' +
  '   Source of truth: the per-screen .html files. After editing\n' +
  '   any of them, regenerate with:  node build-templates.js\n' +
  '   Generated: ' + new Date().toISOString() + ' */\n' +
  'window.__LOCAL_TEMPLATES = {\n';

for (const name of SCREENS) {
  const file = path.join(TEMPLATES_DIR, name + '.html');
  const html = fs.readFileSync(file, 'utf8');
  out += '  ' + JSON.stringify(name) + ': ' + JSON.stringify(html) + ',\n';
  console.log('bundled ' + name + '.html (' + html.length + ' chars)');
}

out += '};\n';

fs.writeFileSync(OUTPUT_FILE, out);
console.log('wrote ' + path.relative(process.cwd(), OUTPUT_FILE));

/* Program modules may ship their own markup for a shared screen
   (templates/modules/<module>/<name>.html — Executive Readiness has its own
   Home and Learn). Those are bundled under "<module>:<name>", which is the key
   Modules.templateKey() asks for. Discovered from the folder, so a new module
   needs no edit here.

   Each module gets a bundle of its OWN, js/templates-local/<module>.js, and
   index.php adds only the open program's file to the page (12 Oct 2026). They
   used to be in templates-local.js with everything else, so every program
   downloaded every other program's screens: AI Governance's and Executive
   Readiness's home screens carry ~525 KB of embedded pictures between them,
   and the Innovation Pipeline was paying for all of it before its sign-in
   screen could appear. Bundles of modules that no longer exist are removed. */
const MODULES_DIR = path.join(TEMPLATES_DIR, 'modules');
const MODULE_OUT_DIR = path.join(__dirname, '..', 'js', 'templates-local');
fs.mkdirSync(MODULE_OUT_DIR, { recursive: true });
const written = {};
if (fs.existsSync(MODULES_DIR)) {
  for (const mod of fs.readdirSync(MODULES_DIR).sort()) {
    const dir = path.join(MODULES_DIR, mod);
    if (!fs.statSync(dir).isDirectory()) continue;
    let modOut =
      '/* AUTO-GENERATED by build-templates.js — DO NOT EDIT BY HAND.\n' +
      '   The ' + mod + ' program\'s own screens, merged into the shared bundle\n' +
      '   (templates-local.js, which loads first). Generated: ' + new Date().toISOString() + ' */\n' +
      '(function (T) {\n';
    let count = 0;
    for (const f of fs.readdirSync(dir).sort()) {
      if (!f.endsWith('.html')) continue;
      const name = f.slice(0, -5);
      const html = fs.readFileSync(path.join(dir, f), 'utf8');
      modOut += '  T[' + JSON.stringify(mod + ':' + name) + '] = ' + JSON.stringify(html) + ';\n';
      console.log('bundled ' + mod + '/' + f + ' (' + html.length + ' chars)');
      count++;
    }
    if (!count) continue;
    modOut += '})(window.__LOCAL_TEMPLATES = window.__LOCAL_TEMPLATES || {});\n';
    const file = path.join(MODULE_OUT_DIR, mod + '.js');
    fs.writeFileSync(file, modOut);
    written[mod + '.js'] = true;
    console.log('wrote ' + path.relative(process.cwd(), file));
  }
}
for (const f of fs.readdirSync(MODULE_OUT_DIR)) {
  if (f.endsWith('.js') && !written[f]) {
    fs.unlinkSync(path.join(MODULE_OUT_DIR, f));
    console.log('removed stale ' + f);
  }
}
